export type BangladeshDistrict = (typeof bangladeshDistricts)[number];

export const getCanonicalDistrict = (value?: string | null) => {
  if (!value) return "";

  return (
    bangladeshDistricts.find(
      (district) => district.toLowerCase() === value.trim().toLowerCase(),
    ) ?? ""
  );
};
